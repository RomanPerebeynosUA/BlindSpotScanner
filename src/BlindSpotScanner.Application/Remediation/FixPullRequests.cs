using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using BlindSpotScanner.Application.GitHub;
using BlindSpotScanner.Application.Llm;
using BlindSpotScanner.Application.Reports;
using BlindSpotScanner.Application.Scanning;
using BlindSpotScanner.Domain.Entities;
using BlindSpotScanner.Domain.Enums;
using BlindSpotScanner.Domain.Reports;

namespace BlindSpotScanner.Application.Remediation;

/// <param name="Enabled">Pull requests are on and a GitHub token is configured (read-only otherwise, D25).</param>
public sealed record FixDefaults(bool Enabled, string PublicUrl);

/// <param name="Original">The file's content at the scanned commit, for a modify (the diff's left side).</param>
public sealed record FixDraftFile(string Path, FixAction Action, string Content, string? Original);

public sealed record FixDraft(
    IReadOnlyList<FixDraftFile> Files,
    string Rationale,
    IReadOnlyList<string> Assumptions,
    IReadOnlyList<string> RiskNotes,
    string Branch,
    string Title,
    string Body,
    decimal CostUsd,
    RemediationAction? Existing);

public enum FixStatus
{
    Ok,
    NotFound,
    NoReport,
    Disabled,
    NotFixable,
    NoContext,
    Declined,
    Rejected,
    FilesChanged,
    Exists,
}

/// <param name="Reasons">Guard violations or LLM errors (Rejected), the LLM's rationale (Declined), or the changed paths (FilesChanged).</param>
public sealed record FixResult<T>(FixStatus Status, T? Value = default, IReadOnlyList<string>? Reasons = null, RemediationAction? Existing = null);

/// <summary>
/// Doc 09 fix pull requests: context at the run's commit, <c>prompts/generate-fix.md</c> with the
/// static guard as its validation (a violation re-asks the LLM), an editable draft, and a draft PR
/// opened only on the user's explicit request (principle 8).
/// </summary>
public sealed partial class FixPullRequests(
    IScanRequestStore runs,
    IRemediationStore store,
    FixContextBuilder contexts,
    IFixGuard guard,
    ILlmClient llm,
    IGitHubClient github,
    FixDefaults defaults)
{
    public const string Footer = "Generated by BlindSpotScanner — review before merging; CI must pass.";

    private const int MaxSlug = 60;

    private static readonly FindingKind[] Fixable = [FindingKind.UncoveredEndpoint, FindingKind.WeakTest, FindingKind.FalsePositive, FindingKind.SkippedTest];

    public async Task<FixResult<FixDraft>> PreviewAsync(Guid runId, string findingId, CancellationToken ct)
    {
        var target = await FindAsync(runId, findingId, ct);
        if (target.Status != FixStatus.Ok)
        {
            return new FixResult<FixDraft>(target.Status);
        }

        var (_, run, report, finding, context) = target;
        var input = JsonSerializer.Serialize(Input(finding!, context!), JsonSerializerOptions.Web);
        var existing = context!.BlobShas.Keys.ToHashSet(StringComparer.Ordinal);
        var result = await llm.CompleteAsync(
            new LlmRequest(Prompts.GenerateFix, input, LlmSchemas.Get(Prompts.GenerateFix), output => guard.Check(Files(output), context.TestProjectFolder, existing)),
            ct);
        if (result.Output is not { } answer)
        {
            return new FixResult<FixDraft>(FixStatus.Rejected, Reasons: result.Errors);
        }

        var rationale = answer.GetProperty("rationale").GetString()!;
        var files = Files(answer);
        if (files.Count == 0)
        {
            return new FixResult<FixDraft>(FixStatus.Declined, Reasons: [rationale]);
        }

        var draftFiles = new List<FixDraftFile>();
        foreach (var file in files)
        {
            var original = file.Action == FixAction.Modify
                ? await github.GetBlobTextAsync(report!.Meta.Repo.Owner, report.Meta.Repo.Name, context.BlobShas[file.Path], ct)
                : null;
            draftFiles.Add(new FixDraftFile(file.Path, file.Action, file.Content, original));
        }

        var assumptions = Strings(answer, "assumptions");
        var jira = await store.FindActionAsync(run!.RepositoryId, finding!.StableKey, ActionType.JiraTicket, ct);
        var body = Body(answer.GetProperty("prBody").GetString()!, rationale, assumptions, finding, jira, runId);
        var draft = new FixDraft(
            draftFiles,
            rationale,
            assumptions,
            Strings(answer, "riskNotes"),
            Branch(finding.StableKey, report!.Meta.CommitSha),
            answer.GetProperty("prTitle").GetString()!,
            body,
            result.Usage.CostUsd,
            await store.FindActionAsync(run.RepositoryId, finding.StableKey, ActionType.PullRequest, ct));
        return new FixResult<FixDraft>(FixStatus.Ok, draft);
    }

    /// <summary>Everything preview and create both need, checked in the same order (D25).</summary>
    private async Task<(FixStatus Status, ScanRun? Run, IntegrationReport? Report, ReportFinding? Finding, FixContext? Context)> FindAsync(
        Guid runId, string findingId, CancellationToken ct)
    {
        if (!defaults.Enabled)
        {
            return (FixStatus.Disabled, null, null, null, null);
        }

        if (await runs.FindRunAsync(runId, ct) is not { } run)
        {
            return (FixStatus.NotFound, null, null, null, null);
        }

        if (run is not { Status: RunStatus.Succeeded, ReportJson: { } json })
        {
            return (FixStatus.NoReport, null, null, null, null);
        }

        var report = ReportJsonSerializer.Deserialize(json);
        if (report.Findings.SingleOrDefault(f => f.Id == findingId) is not { } finding)
        {
            return (FixStatus.NotFound, null, null, null, null);
        }

        if (!Fixable.Contains(finding.Kind))
        {
            return (FixStatus.NotFixable, null, null, null, null);
        }

        return await contexts.BuildAsync(report, finding, ct) is { } context
            ? (FixStatus.Ok, run, report, finding, context)
            : (FixStatus.NoContext, null, null, null, null);
    }

    /// <summary>The prompt's input shape (<c>prompts/generate-fix.md</c>).</summary>
    private static object Input(ReportFinding finding, FixContext context)
    {
        object? endpoint = null;
        if (finding is { Kind: FindingKind.UncoveredEndpoint, Detail: [var display, ..] } && display.Split(' ', 2) is [var method, var route])
        {
            endpoint = new { method, route };
        }

        static object File(SourceFile f) => new { path = f.Path, content = f.Content };
        return new
        {
            finding = new { kind = finding.Kind.ToString(), stableKey = finding.StableKey, endpoint, detail = finding.Detail ?? [] },
            controllerSource = context.Controller is null ? null : File(context.Controller),
            siblingTests = context.SiblingTests.Select(File),
            fixtures = context.Fixtures.Select(File),
            testProjectFile = File(context.TestProjectFile),
            targetFolder = context.TargetFolder,
        };
    }

    private static List<FixFile> Files(JsonElement answer) =>
        [.. answer.GetProperty("files").EnumerateArray().Select(f => new FixFile(
            f.GetProperty("path").GetString()!,
            f.GetProperty("action").GetString() == "modify" ? FixAction.Modify : FixAction.Create,
            f.GetProperty("content").GetString()!))];

    private static List<string> Strings(JsonElement answer, string property) =>
        [.. answer.GetProperty(property).EnumerateArray().Select(s => s.GetString()!)];

    /// <summary><c>coverage/fix-&lt;stableKey-slug&gt;-&lt;shortsha&gt;</c> (doc 09).</summary>
    public static string Branch(string stableKey, string commitSha)
    {
        var slug = NonSlug().Replace(stableKey.ToLowerInvariant(), "-").Trim('-');
        slug = slug.Length > MaxSlug ? slug[..MaxSlug].TrimEnd('-') : slug;
        return $"coverage/fix-{slug}-{commitSha[..Math.Min(7, commitSha.Length)]}";
    }

    private string Body(string prBody, string rationale, IReadOnlyList<string> assumptions, ReportFinding finding, RemediationAction? jira, Guid runId)
    {
        var body = new StringBuilder(prBody.TrimEnd());
        body.Append("\n\n## Why\n").Append(rationale);
        if (assumptions.Count > 0)
        {
            body.Append("\n\n## Assumptions");
            foreach (var assumption in assumptions)
            {
                body.Append("\n- ").Append(assumption);
            }
        }

        body.Append("\n\n## Finding\n").Append(finding.Headline).Append(" (`").Append(finding.StableKey).Append("`)");
        if (jira is not null)
        {
            body.Append("\n\nJira: [").Append(jira.ExternalKey).Append("](").Append(jira.Url).Append(')');
        }

        body.Append("\n\n[View the report](").Append(defaults.PublicUrl.TrimEnd('/')).Append("/runs/").Append(runId).Append(')');
        body.Append("\n\n").Append(Footer);
        return body.ToString();
    }

    [GeneratedRegex("[^a-z0-9]+")]
    private static partial Regex NonSlug();
}
