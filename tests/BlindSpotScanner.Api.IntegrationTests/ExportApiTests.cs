using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using FluentAssertions;

namespace BlindSpotScanner.Api.IntegrationTests;

/// <summary>Doc 11 M11 export: the stored report as JSON, or a printable HTML page; Viewers may export.</summary>
public class ExportApiTests(QueueOnlyApiFactory factory) : IClassFixture<QueueOnlyApiFactory>
{
    private async Task<Guid> SeedAsync()
    {
        var repositoryId = await factory.SeedRepositoryAsync();
        var runId = Guid.NewGuid();
        await factory.SeedSucceededRunAsync(repositoryId, "sample-report.json", runId, null);
        return runId;
    }

    [Fact]
    public async Task Export_Json_ReturnsStoredReportAsAttachment()
    {
        // Arrange
        var runId = await SeedAsync();
        using var client = factory.CreateClient("Viewer");

        // Act
        using var response = await client.GetAsync($"/api/runs/{runId}/export");

        // Assert
        var body = await response.Content.ReadFromJsonAsync<JsonElement>();
        new
        {
            response.StatusCode,
            Type = response.Content.Headers.ContentType?.MediaType,
            File = response.Content.Headers.ContentDisposition?.FileName?.Trim('"'),
            RunId = body.GetProperty("meta").GetProperty("runId").GetGuid(),
        }.Should().Be(new { StatusCode = HttpStatusCode.OK, Type = (string?)"application/json", File = (string?)"report-example-org-bookstore-api-a1b2c3d.json", RunId = runId });
    }

    [Fact]
    public async Task Export_Html_ReturnsTextHtmlAttachment()
    {
        // Arrange
        var runId = await SeedAsync();
        using var client = factory.CreateClient("Viewer");

        // Act
        using var response = await client.GetAsync($"/api/runs/{runId}/export?format=html");

        // Assert
        var html = await response.Content.ReadAsStringAsync();
        new
        {
            Type = response.Content.Headers.ContentType?.MediaType,
            File = response.Content.Headers.ContentDisposition?.FileName?.Trim('"'),
            Footer = html.Contains("Generated by BlindSpotScanner", StringComparison.Ordinal),
        }.Should().Be(new { Type = (string?)"text/html", File = (string?)"report-example-org-bookstore-api-a1b2c3d.html", Footer = true });
    }

    [Fact]
    public async Task Export_QueuedRun_Returns409()
    {
        // Arrange
        var repositoryId = await factory.SeedRepositoryAsync();
        using var client = factory.CreateClient();
        var runId = (await (await client.PostAsJsonAsync($"/api/repositories/{repositoryId}/scans", new { })).Content.ReadFromJsonAsync<JsonElement>()).GetProperty("runId").GetGuid();

        // Act
        using var response = await client.GetAsync($"/api/runs/{runId}/export");

        // Assert
        response.StatusCode.Should().Be(HttpStatusCode.Conflict);
    }

    [Fact]
    public async Task Export_UnknownFormat_Returns400()
    {
        // Arrange
        var runId = await SeedAsync();
        using var client = factory.CreateClient();

        // Act
        using var response = await client.GetAsync($"/api/runs/{runId}/export?format=pdf");

        // Assert
        response.StatusCode.Should().Be(HttpStatusCode.BadRequest);
    }
}
