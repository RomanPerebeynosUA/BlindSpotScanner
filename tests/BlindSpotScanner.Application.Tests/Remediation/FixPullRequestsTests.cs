namespace BlindSpotScanner.Application.Tests.Remediation;

public class FixPullRequestsTests
{
    private const string NewTestPath = "tests/Bookstore.IntegrationTests/CancelOrderTests.cs";
    private const string Footer = "Generated by BlindSpotScanner — review before merging; CI must pass.";
    private static readonly DateTimeOffset Now = new(2026, 11, 17, 12, 0, 0, TimeSpan.Zero);

    private readonly RunStore _runs = new();
    private readonly ActionStore _store = new();
    private readonly FixContextBuilderTests.TreeGitHub _github = new(FixContextBuilderTests.BookstoreFiles);
    private readonly RecordingPulls _pulls = new();
    private readonly ValidatingLlm _llm = new();
    private readonly Guid _runId;
    private readonly Guid _repositoryId = Guid.NewGuid();
    private bool _enabled = true;

    public FixPullRequestsTests()
    {
        _runId = AddRun(Fixtures.Current);
        _llm.Answers.Enqueue(Answer(NewTestPath, "create"));
    }

    private FixPullRequests Fixes => new(
        _runs, _store, new FixContextBuilder(_github), new PathGuard(), _llm, _github, new FixDefaults(_enabled, "http://localhost:8080"));

    private Guid AddRun(IntegrationReport report)
    {
        var meta = report.Meta;
        var run = new ScanRun(meta.RunId, _repositoryId, meta.Branch, meta.CommitSha, meta.ModelId, meta.PromptSetVersion, meta.ProfileVersion);
        run.RecordReport(report);
        run.Succeed();
        _runs.Runs.Add(run);
        return run.Id;
    }

    internal static string Answer(string path, string action, string content = "public class CancelOrderTests { }") => JsonSerializer.Serialize(new
    {
        files = new[] { new { path, action, content } },
        rationale = "Covers order cancellation.",
        assumptions = new[] { "Orders are seeded through DbFixture." },
        riskNotes = Array.Empty<string>(),
        prTitle = "test: add integration test for POST api/orders/{id}/cancel",
        prBody = "Adds an integration test.",
    });

    private Task<FixResult<FixDraft>> PreviewAsync(string findingId = "f2") => Fixes.PreviewAsync(_runId, findingId, CancellationToken.None);

    [Fact]
    public async Task PreviewAsync_UncoveredEndpoint_ReturnsDraftWithBranchAndFooter()
    {
        // Act
        var draft = (await PreviewAsync()).Value!;

        // Assert
        new { draft.Branch, draft.Title, EndsWithFooter = draft.Body.EndsWith(Footer, StringComparison.Ordinal), File = draft.Files.Single().Path }.Should().Be(new
        {
            Branch = "coverage/fix-uncovered-endpoint-post-api-orders-cancel-a1b2c3d",
            Title = "test: add integration test for POST api/orders/{id}/cancel",
            EndsWithFooter = true,
            File = NewTestPath,
        });
    }

    [Fact]
    public async Task PreviewAsync_UncoveredEndpoint_SendsPromptInputShape()
    {
        // Act
        await PreviewAsync();

        // Assert
        var input = JsonDocument.Parse(_llm.Requests.Single().InputJson).RootElement;
        new
        {
            Prompt = _llm.Requests.Single().Prompt,
            Method = input.GetProperty("finding").GetProperty("endpoint").GetProperty("method").GetString(),
            Route = input.GetProperty("finding").GetProperty("endpoint").GetProperty("route").GetString(),
            Target = input.GetProperty("targetFolder").GetString(),
            Controller = input.GetProperty("controllerSource").GetProperty("path").GetString(),
        }.Should().Be(new
        {
            Prompt = Prompts.GenerateFix,
            Method = "POST",
            Route = "api/orders/{id}/cancel",
            Target = "tests/Bookstore.IntegrationTests/",
            Controller = "src/Bookstore.Api/Controllers/OrdersController.cs",
        });
    }

    [Fact]
    public async Task PreviewAsync_ModifyFile_IncludesOriginal()
    {
        // Arrange
        _llm.Answers.Clear();
        _llm.Answers.Enqueue(Answer("tests/Bookstore.IntegrationTests/BooksApiTests.cs", "modify"));

        // Act
        var file = (await PreviewAsync("f3")).Value!.Files.Single();

        // Assert
        new { file.Action, file.Original }.Should().Be(new { Action = FixAction.Modify, Original = (string?)"// tests/Bookstore.IntegrationTests/BooksApiTests.cs" });
    }

    [Fact]
    public async Task PreviewAsync_GuardFailsEveryAttempt_ReturnsRejectedWithReasons()
    {
        // Arrange
        _llm.Answers.Clear();
        for (var i = 0; i < 3; i++)
        {
            _llm.Answers.Enqueue(Answer("src/Bookstore.Api/Controllers/OrdersController.cs", "modify"));
        }

        // Act
        var result = await PreviewAsync();

        // Assert
        new { result.Status, Reasons = string.Join("|", result.Reasons!) }
            .Should().Be(new { Status = FixStatus.Rejected, Reasons = "src/Bookstore.Api/Controllers/OrdersController.cs: outside the test project tests/Bookstore.IntegrationTests" });
    }

    [Fact]
    public async Task PreviewAsync_GuardFailsOnce_RetriesAndSucceeds()
    {
        // Arrange
        _llm.Answers.Clear();
        _llm.Answers.Enqueue(Answer("src/Bookstore.Api/Controllers/OrdersController.cs", "modify"));
        _llm.Answers.Enqueue(Answer(NewTestPath, "create"));

        // Act
        var result = await PreviewAsync();

        // Assert
        new { result.Status, File = result.Value!.Files.Single().Path }.Should().Be(new { Status = FixStatus.Ok, File = NewTestPath });
    }

    [Fact]
    public async Task PreviewAsync_EmptyFiles_ReturnsDeclinedWithRationale()
    {
        // Arrange
        _llm.Answers.Clear();
        _llm.Answers.Enqueue("""{"files":[],"rationale":"The skip reason is still valid.","assumptions":[],"riskNotes":[],"prTitle":"x","prBody":""}""");

        // Act
        var result = await PreviewAsync();

        // Assert
        new { result.Status, Reason = result.Reasons!.Single() }.Should().Be(new { Status = FixStatus.Declined, Reason = "The skip reason is still valid." });
    }

    [Fact]
    public async Task PreviewAsync_UncoveredSeam_ReturnsNotFixable()
    {
        // Act
        var result = await PreviewAsync("f4");

        // Assert
        new { result.Status, Calls = _llm.Requests.Count }.Should().Be(new { Status = FixStatus.NotFixable, Calls = 0 });
    }

    [Fact]
    public async Task PreviewAsync_Disabled_ReturnsDisabled()
    {
        // Arrange
        _enabled = false;

        // Act
        var result = await PreviewAsync();

        // Assert
        result.Status.Should().Be(FixStatus.Disabled);
    }

    [Fact]
    public async Task PreviewAsync_JiraTicketExists_BodyLinksIt()
    {
        // Arrange
        _store.Actions.Add(Action(ActionType.JiraTicket, "BSS-3", "https://example.atlassian.net/browse/BSS-3"));

        // Act
        var draft = (await PreviewAsync()).Value!;

        // Assert
        draft.Body.Should().Contain("Jira: [BSS-3](https://example.atlassian.net/browse/BSS-3)");
    }

    private RemediationAction Action(ActionType type, string key, string url) => new()
    {
        Id = Guid.NewGuid(),
        RepositoryId = _repositoryId,
        StableKey = "uncovered-endpoint:POST api/orders/{}/cancel",
        CreatedFromFindingId = Guid.NewGuid(),
        Type = type,
        ExternalKey = key,
        Url = url,
        Status = "Open",
        StatusCheckedAt = Now,
        CreatedAt = Now,
        CreatedBy = "anonymous",
    };

    /// <summary>Rejects anything outside the bookstore test project, like the real guard's first rule.</summary>
    private sealed class PathGuard : IFixGuard
    {
        public IReadOnlyList<string> Check(IReadOnlyList<FixFile> files, string testProjectFolder, IReadOnlySet<string> existingPaths) =>
            [.. files.Where(f => !f.Path.StartsWith(testProjectFolder + "/", StringComparison.Ordinal)).Select(f => $"{f.Path}: outside the test project {testProjectFolder}")];
    }

    /// <summary>Plays queued answers like the real client: an answer failing Validate is re-asked, at most 3 attempts.</summary>
    internal sealed class ValidatingLlm : ILlmClient
    {
        public Queue<string> Answers { get; } = new();

        public List<LlmRequest> Requests { get; } = [];

        public Task<LlmResult> CompleteAsync(LlmRequest request, CancellationToken ct)
        {
            Requests.Add(request);
            IReadOnlyList<string> errors = [];
            for (var attempt = 0; attempt < 3 && Answers.Count > 0; attempt++)
            {
                var output = JsonDocument.Parse(Answers.Dequeue()).RootElement.Clone();
                errors = request.Validate?.Invoke(output) ?? [];
                if (errors.Count == 0)
                {
                    return Task.FromResult(new LlmResult(output, [], new LlmUsage(1000, 400, 0.04m), FromCache: false));
                }
            }

            return Task.FromResult(new LlmResult(null, errors, new LlmUsage(3000, 1200, 0.12m), FromCache: false));
        }
    }

    /// <summary>Records each write in order; <see cref="FailOn"/> makes that call throw.</summary>
    internal sealed class RecordingPulls : IGitHubPullRequests
    {
        public List<string> Calls { get; } = [];

        public string? FailOn { get; set; }

        private T Record<T>(string call, T result)
        {
            Calls.Add(call);
            return call == FailOn ? throw new HttpRequestException($"GitHub failed on {call}") : result;
        }

        public Task<string> GetCommitTreeShaAsync(string owner, string name, string commitSha, CancellationToken ct) => Task.FromResult(Record("tree-of-head", "base-tree"));

        public Task<string> CreateBlobAsync(string owner, string name, string content, CancellationToken ct) => Task.FromResult(Record("blob", "blob-sha"));

        public Task<string> CreateTreeAsync(string owner, string name, string baseTreeSha, IReadOnlyList<(string Path, string BlobSha)> files, CancellationToken ct) =>
            Task.FromResult(Record("tree", "new-tree"));

        public Task<string> CreateCommitAsync(string owner, string name, string message, string treeSha, string parentSha, CancellationToken ct) =>
            Task.FromResult(Record("commit", "new-commit"));

        public Task CreateBranchAsync(string owner, string name, string branch, string commitSha, CancellationToken ct) => Task.FromResult(Record("ref", 0));

        public Task<OpenedPullRequest> CreateDraftPullRequestAsync(string owner, string name, string title, string body, string head, string baseBranch, CancellationToken ct) =>
            Task.FromResult(Record("pull", new OpenedPullRequest(7, "https://github.com/example-org/bookstore-api/pull/7")));

        public Task AddLabelsAsync(string owner, string name, int number, IReadOnlyList<string> labels, CancellationToken ct) => Task.FromResult(Record("labels", 0));

        public Dictionary<int, string> Statuses { get; } = [];

        public Task<string> GetPullRequestStatusAsync(string owner, string name, int number, CancellationToken ct) => Task.FromResult(Statuses[number]);
    }

    internal sealed class Clock(DateTimeOffset now) : TimeProvider
    {
        public override DateTimeOffset GetUtcNow() => now;
    }

    internal sealed class ActionStore : IRemediationStore
    {
        public List<RemediationAction> Actions { get; } = [];

        public int Saves { get; private set; }

        public Task<Finding> EnsureFindingAsync(Guid runId, ReportFinding finding, CancellationToken ct) => Task.FromResult(new Finding
        {
            Id = Guid.NewGuid(), ScanRunId = runId, ReportFindingId = finding.Id, Kind = finding.Kind, Severity = finding.Severity,
            StableKey = finding.StableKey, Headline = finding.Headline, Detail = [], Evidence = [],
        });

        public Task<RemediationAction?> FindActionAsync(Guid repositoryId, string stableKey, ActionType type, CancellationToken ct) =>
            Task.FromResult(Actions.Where(a => a.RepositoryId == repositoryId && a.StableKey == stableKey && a.Type == type).MaxBy(a => a.CreatedAt));

        public Task AddActionAsync(RemediationAction action, CancellationToken ct)
        {
            Actions.Add(action);
            return Task.CompletedTask;
        }

        public Task<IReadOnlyList<RemediationAction>> ActionsAsync(Guid repositoryId, CancellationToken ct) =>
            Task.FromResult<IReadOnlyList<RemediationAction>>([.. Actions.Where(a => a.RepositoryId == repositoryId)]);

        public Task SaveChangesAsync(CancellationToken ct)
        {
            Saves++;
            return Task.CompletedTask;
        }
    }

    internal sealed class RunStore : IScanRequestStore
    {
        public List<ScanRun> Runs { get; } = [];

        public Task<ScanRun?> FindRunAsync(Guid runId, CancellationToken ct) => Task.FromResult(Runs.SingleOrDefault(r => r.Id == runId));

        public Task<bool> RepositoryExistsAsync(Guid repositoryId, CancellationToken ct) => throw new NotSupportedException();

        public Task<int?> LatestProfileVersionAsync(Guid repositoryId, CancellationToken ct) => throw new NotSupportedException();

        public Task<IReadOnlyList<ScanStep>> StepsAsync(Guid runId, CancellationToken ct) => throw new NotSupportedException();

        public Task<bool> SaveChangesAsync(CancellationToken ct) => throw new NotSupportedException();

        public Task ReloadAsync(ScanRun run, CancellationToken ct) => throw new NotSupportedException();
    }
}
