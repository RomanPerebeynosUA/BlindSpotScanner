using BlindSpotScanner.Application.Reports;
using FluentAssertions;

namespace BlindSpotScanner.Application.Tests.Reports;

/// <summary>The printable report (doc 11 M11 export): self-contained, no scripts, every report string encoded.</summary>
public class ReportHtmlRendererTests
{
    [Fact]
    public void Render_SampleReport_HasSectionsInOrder()
    {
        // Act
        var html = ReportHtmlRenderer.Render(Fixtures.Current);

        // Assert
        var order = new[] { "example-org/bookstore-api", "Quality score", "Top risks", "Endpoint coverage", "Quality scorecard", "Findings", "Generated by BlindSpotScanner" }
            .Select(s => html.IndexOf(s, StringComparison.Ordinal)).ToList();
        new { AllPresent = order.All(i => i >= 0), InOrder = order.SequenceEqual(order.Order()) }.Should().Be(new { AllPresent = true, InOrder = true });
    }

    [Fact]
    public void Render_FindingWithMarkup_EncodesItAndHasNoScript()
    {
        // Arrange (finding text is LLM-authored)
        const string hostile = "<script>alert(1)</script>\"><img src=x onerror=alert(1)>";
        var report = Fixtures.Current with { Findings = [.. Fixtures.Current.Findings.Select(f => f with { Headline = hostile })] };

        // Act
        var html = ReportHtmlRenderer.Render(report);

        // Assert
        new
        {
            Script = html.Contains("<script", StringComparison.OrdinalIgnoreCase),
            Img = html.Contains("<img", StringComparison.OrdinalIgnoreCase),
            Encoded = html.Contains("&lt;script&gt;alert(1)&lt;/script&gt;", StringComparison.Ordinal),
        }.Should().Be(new { Script = false, Img = false, Encoded = true });
    }

    [Fact]
    public void Render_UnscorableDimension_ShowsNA()
    {
        // Arrange
        var report = Fixtures.Current with { Scorecard = [.. Fixtures.Current.Scorecard.Select(d => d with { Score = null, Scorable = false })] };

        // Act
        var html = ReportHtmlRenderer.Render(report);

        // Assert
        html.Should().Contain("<td>N/A</td>");
    }

    [Fact]
    public void Render_StatusIsText_NotColourAlone()
    {
        // Act
        var html = ReportHtmlRenderer.Render(Fixtures.Current);

        // Assert
        html.Should().Contain("<td class=\"status s-none\">none</td>");
    }
}
